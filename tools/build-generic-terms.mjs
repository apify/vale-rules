// Build the checked-in Vale rule from shared contexts and term data.
// Runtime consumers need only the generated YAML, not Node.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const navigationGuard = String.raw`(?<!\b(?i:click|select|choose|open|view|abort|go to|navigate to)(?:[ \t]+the)?[ \t]+)`;
const suffixGuard = String.raw`(?!:|,[^.!?\n]*\boptions\b|[ \t]+(?:[A-Z]|(?:tabs?|buttons?|pages?|section|dialog|node|menu|screen|field|option|docs|documentation|URL|basics|list)\b))`;
const contexts = {
  ai: String.raw`(?:^|(?<=\b(?:[Aa]n?|[Cc]ustom|[Gg]eneric|[Ss]imple|[Nn]ew|[Aa]ny|[Ee]ach|[Tt]he|[Yy]our|[Oo]ur|[Tt]his|[Tt]hat)[ \t]+))`,
  technical: String.raw`(?:^|(?<=\b(?:[a-z][\w-]*|[Uu]se|[Cc]onfigure|[Ii]nstall)[ \t]+))`,
  feature: String.raw`(?<=\b(?<!:::)(?:[a-z][\w-]*|[Tt]he|[Aa]n?|[Ee]ach|[Yy]our|[Oo]ur|[Tt]his|[Tt]hat)[ \t]+)`,
  descriptive: String.raw`(?<=\b(?:[Aa]n?|[Cc]ustom|[Gg]eneric|[Ss]imple|[Bb]asic|[Yy]our|[Oo]ur|[Ee]ach|[Tt]his)[ \t]+)`,
};

// Context, singular pattern, replacement, and whether to include a plural.
const terms = [
  ["ai", String.raw`AI Agent`, "AI agent", true],
  ["technical", String.raw`MCP Server`, "MCP server", true],
  ["technical", String.raw`MCP Connector`, "MCP connector", true],
  ["technical", String.raw`API Endpoint`, "API endpoint", true],
  ["feature", String.raw`Run`, "run", true],
  ["feature", String.raw`Build`, "build", true],
  ["feature", String.raw`Dataset`, "dataset", true],
  ["feature", String.raw`Key-[Vv]alue [Ss]tore`, "key-value store", true],
  ["feature", String.raw`Request [Qq]ueue`, "request queue", true],
  ["feature", String.raw`Web [Ss]craping`, "web scraping", false],
  ["descriptive", String.raw`Web [Ss]craper`, "web scraper", true],
  ["descriptive", String.raw`Proxy [Ss]erver`, "proxy server", true],
  ["descriptive", String.raw`Crawler`, "crawler", true],
  ["descriptive", String.raw`Scraper`, "scraper", true],
  ["feature", String.raw`Task`, "task", true],
  ["feature", String.raw`Schedule`, "schedule", true],
];

const header = "extends: substitution\nlevel: suggestion\nignorecase: false\ncapitalize: false\naction:\n  name: replace\nmessage: \"Use '%s' instead of '%s' for a generic term. Preserve official product and interface names.\"\nnonword: true\nvocab: false\nscope: text & ~frontmatter & ~heading & ~link & ~alt & ~strong & ~emphasis\n\n";
let output = header + '# Generated by node tools/build-generic-terms.mjs; edit the shared guards there.\nswap:\n';
for (const [context, term, replacement, plural] of terms) {
  for (const ending of plural ? ['', 's'] : ['']) {
    const pattern = navigationGuard + contexts[context] + term + ending + String.raw`\b` + suffixGuard;
    output += `  '${pattern}': '${replacement}${ending}'\n`;
  }
}
const target = fileURLToPath(new URL('../styles/Apify/GenericTechnicalTerms.yml', import.meta.url));
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    throw new Error('GenericTechnicalTerms.yml is stale; run node tools/build-generic-terms.mjs');
  }
} else {
  writeFileSync(target, output);
}
